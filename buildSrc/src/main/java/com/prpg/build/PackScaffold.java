package com.prpg.build;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;

/**
 * Writes a new act pack that boots: a pack.yaml declaring the act, a stub TMX holding only geography
 * (terrain, a spawn, a marker), and the act's Ink story, which is where everything else lives: where
 * the act begins, its state, what is staged where, the journal, and an opening scene. Used by the root
 * {@code newPack} task. Pure JDK.
 */
public final class PackScaffold {

    private PackScaffold() {}

    public static void scaffold(File packDir, String id, String kind, int order) throws IOException {
        for (String dir : new String[]{"ink", "narrative", "maps", "activities"}) {
            new File(packDir, dir).mkdirs();
        }

        String mapId = id + "_start";
        write(new File(packDir, "pack.yaml"), """
                # Pack manifest (metadata authored; `files:` regenerated by generatePackManifests / shipPack).
                # Everything that happens in the act is in ink/%1$s.ink.
                schemaVersion: 1
                id: %1$s
                kind: %2$s
                version: 1
                bundled: false          # true = ships inside the app; false = DLC zip (shipPack)
                requiresBaseline: true
                baselineVersion: ">=1"
                provides:
                  - id: %1$s
                    title: TODO title for %1$s
                    order: %3$d
                files:
                """.formatted(id, kind, order));

        write(new File(packDir, "ink/" + id + ".ink"), """
                # entry: %2$s start
                INCLUDE ../../baseline/ink/common/bridge.ink
                INCLUDE ../../baseline/ink/common/world.ink

                // The `# entry:` line above says where the act begins (map, then spawn). It must stay the
                // file's first line. Everything the act does is in this file; see docs/content-guide.md.

                // Author preview entry point (Inky only). In-game, the engine diverts straight into a
                // knot by name, so this top-level flow never runs during play.
                -> author_menu

                // --- state: every variable this act (and only this act) uses ---
                VAR %1$s_met_stranger = false

                // --- what staged ids look like: define(id, sprite, color) ---
                === function cast() ===
                ~ define("stranger", "npc", "7A6E9B")

                // --- who and what is where: actor / thing / zone / lock, at a map's named markers ---
                === function stage() ===
                ~ actor("stranger", "%2$s", "centre", -> stranger)

                // --- the journal: quest(title), then step(text, done) ---
                === function journal() ===
                ~ quest("TODO quest title")
                ~ step("Speak to the stranger.", %1$s_met_stranger)

                // --- runs each time the act is entered ---
                === act_start ===
                >>> fade out 0
                >>> fade in 1
                A new act begins here. # speaker: (you)
                -> END

                === stranger ===
                ~ %1$s_met_stranger = true
                Replace this knot, and add one per thing the player can talk to. # speaker: Stranger
                -> END

                === author_menu ===
                + [act_start] -> act_start
                + [stranger] -> stranger
                + [(what is staged right now)] -> preview_world

                === preview_world ===
                ~ stage()
                ~ journal()
                -> author_menu
                """.formatted(id, mapId));

        write(new File(packDir, "maps/" + mapId + ".tmx"), stubMap());
    }

    /**
     * A 14x12 walled grass field using the baseline placeholder tileset: every layer the engine
     * reads, one spawn named {@code start}, and one marker named {@code centre} to stage against.
     * Only geography: the story stages everything else.
     */
    static String stubMap() {
        int w = 14;
        int h = 12;
        // basic.tsx gids: 1 = grass, 9 = wall (see PlaceholderArt for the tile table).
        StringBuilder ground = new StringBuilder();
        StringBuilder walls = new StringBuilder();
        StringBuilder collision = new StringBuilder();
        for (int y = 0; y < h; y++) {
            for (int x = 0; x < w; x++) {
                boolean edge = x == 0 || y == 0 || x == w - 1 || y == h - 1;
                ground.append(1);
                walls.append(edge ? 9 : 0);
                collision.append(edge ? 1 : 0);
                if (x < w - 1 || y < h - 1) {
                    ground.append(',');
                    walls.append(',');
                    collision.append(',');
                }
            }
            ground.append('\n');
            walls.append('\n');
            collision.append('\n');
        }
        return """
                <?xml version="1.0" encoding="UTF-8"?>
                <map version="1.10" tiledversion="1.10.2" orientation="orthogonal" renderorder="right-down" width="%1$d" height="%2$d" tilewidth="16" tileheight="16" infinite="0" nextlayerid="11" nextobjectid="3">
                 <tileset firstgid="1" source="../../baseline/tilesets/basic.tsx"/>
                 <layer id="1" name="ground" width="%1$d" height="%2$d">
                  <data encoding="csv">
                %3$s  </data>
                 </layer>
                 <layer id="2" name="walls" width="%1$d" height="%2$d">
                  <data encoding="csv">
                %4$s  </data>
                 </layer>
                 <layer id="3" name="collision" width="%1$d" height="%2$d" visible="0">
                  <data encoding="csv">
                %5$s  </data>
                 </layer>
                 <objectgroup id="4" name="spawn">
                  <object id="1" name="start" type="Spawn" x="112" y="96" width="16" height="16"/>
                 </objectgroup>
                 <objectgroup id="5" name="portals"/>
                 <objectgroup id="10" name="markers">
                  <object id="2" name="centre" type="Marker" x="112" y="64" width="16" height="16"/>
                 </objectgroup>
                </map>
                """.formatted(w, h, ground, walls, collision);
    }

    private static void write(File file, String text) throws IOException {
        file.getParentFile().mkdirs();
        Files.writeString(file.toPath(), text, StandardCharsets.UTF_8);
    }
}
