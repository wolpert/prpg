package com.prpg.build;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;

/**
 * Writes a new act pack that boots: a pack.yaml declaring the act and its entry map, a stub TMX with
 * every required layer, a one-knot Ink story, an empty staging file and an empty flags file. Used by
 * the root {@code newPack} task. Pure JDK.
 */
public final class PackScaffold {

    private PackScaffold() {}

    public static void scaffold(File packDir, String id, String kind, int order) throws IOException {
        for (String dir : new String[]{"ink", "narrative", "maps", "staging", "quests", "actors",
                "activities", "flags"}) {
            new File(packDir, dir).mkdirs();
        }
        new File(packDir, "flags").delete(); // flags is a file, not a dir; created below

        String mapId = id + "_start";
        write(new File(packDir, "pack.yaml"), """
                # Pack manifest (metadata authored; `files:` regenerated by generatePackManifests / shipPack).
                schemaVersion: 1
                id: %1$s
                kind: %2$s
                version: 1
                bundled: false          # true = ships inside the app; false = DLC zip (shipPack)
                requiresBaseline: true
                baselineVersion: ">=1"
                provides:
                  - id: %1$s
                    title: TODO title for %1$s
                    order: %3$d
                    entryMap: %4$s      # a TMX in this pack's maps/ the act opens on
                    entrySpawn: start   # a named object in that map's spawn layer
                flags: []               # mirror of flags.yaml (convention)
                requiresFlags: []       # flags this pack reads but another pack declares
                files:
                """.formatted(id, kind, order, mapId));

        write(new File(packDir, "flags.yaml"), """
                # Every flag this pack's content references (Ink set_flag/has_flag, staging when/unless,
                # quest steps, activity on_complete) must be declared here or in another pack's flags.yaml.
                flags: []
                """);

        write(new File(packDir, "ink/" + id + ".ink"), """
                INCLUDE ../../baseline/ink/common/bridge.ink

                // Author preview entry point (Inky only). In-game, dialogue diverts straight into a knot
                // by name, so this top-level flow never runs during play.
                -> author_menu

                === %1$s_open ===
                A new act begins here. Replace this knot, and add one per talking thing. # speaker: Narrator
                -> END

                === author_menu ===
                + [%1$s_open] -> %1$s_open
                """.formatted(id));

        write(new File(packDir, "staging/" + id + ".yaml"), """
                # Who and what is in the world during this act (see docs/content-guide.md, Staging).
                act: %s
                cast: []
                obstacles: []
                items: []
                triggers: []
                props: []
                """.formatted(id));

        write(new File(packDir, "maps/" + mapId + ".tmx"), stubMap());
    }

    /**
     * A 14x12 walled grass field using the baseline placeholder tileset: every layer the engine
     * reads, one spawn named {@code start}, and one marker named {@code centre} to stage against.
     */
    static String stubMap() {
        int w = 14;
        int h = 12;
        // basic.tsx gids: 1 = grass, 9 = wall (see PlaceholderArt for the tile table).
        StringBuilder ground = new StringBuilder();
        StringBuilder walls = new StringBuilder();
        StringBuilder collision = new StringBuilder();
        for (int y = 0; y < h; y++) {
            for (int x = 0; x < w; x++) {
                boolean edge = x == 0 || y == 0 || x == w - 1 || y == h - 1;
                ground.append(1);
                walls.append(edge ? 9 : 0);
                collision.append(edge ? 1 : 0);
                if (x < w - 1 || y < h - 1) {
                    ground.append(',');
                    walls.append(',');
                    collision.append(',');
                }
            }
            ground.append('\n');
            walls.append('\n');
            collision.append('\n');
        }
        return """
                <?xml version="1.0" encoding="UTF-8"?>
                <map version="1.10" tiledversion="1.10.2" orientation="orthogonal" renderorder="right-down" width="%1$d" height="%2$d" tilewidth="16" tileheight="16" infinite="0" nextlayerid="11" nextobjectid="3">
                 <tileset firstgid="1" source="../../baseline/tilesets/basic.tsx"/>
                 <layer id="1" name="ground" width="%1$d" height="%2$d">
                  <data encoding="csv">
                %3$s  </data>
                 </layer>
                 <layer id="2" name="walls" width="%1$d" height="%2$d">
                  <data encoding="csv">
                %4$s  </data>
                 </layer>
                 <layer id="3" name="collision" width="%1$d" height="%2$d" visible="0">
                  <data encoding="csv">
                %5$s  </data>
                 </layer>
                 <objectgroup id="4" name="spawn">
                  <object id="1" name="start" type="Spawn" x="112" y="96" width="16" height="16"/>
                 </objectgroup>
                 <objectgroup id="5" name="portals"/>
                 <objectgroup id="6" name="npcs"/>
                 <objectgroup id="7" name="items"/>
                 <objectgroup id="8" name="activities"/>
                 <objectgroup id="9" name="triggers"/>
                 <objectgroup id="10" name="markers">
                  <object id="2" name="centre" type="Marker" x="112" y="64" width="16" height="16"/>
                 </objectgroup>
                </map>
                """.formatted(w, h, ground, walls, collision);
    }

    private static void write(File file, String text) throws IOException {
        file.getParentFile().mkdirs();
        Files.writeString(file.toPath(), text, StandardCharsets.UTF_8);
    }
}
